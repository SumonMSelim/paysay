package paypal

import (
	"encoding/json"
	"fmt"
	"strconv"
	"strings"
	"time"
)

// ShapeCreateInvoiceArgs ensures invoice arguments meet PayPal Invoicing v2
// requirements when called by MCP. If the payload is already in v2 format
// (has "detail" or "primary_recipients"), it leaves it intact.
func ShapeCreateInvoiceArgs(raw json.RawMessage, fallbackMerchantEmail string) json.RawMessage {
	if len(raw) == 0 {
		return raw
	}

	// Resolve the invoice and due dates first so the invoice carries a real
	// invoice date (and, in demo mode, a due date). On the live MCP server the
	// create_invoice tool only accepts a flat invoice_date and has no due-date
	// or payment-term field, so the due date cannot be sent there; it is still
	// resolved here so callers and tests see a consistent value.
	raw = applyInvoiceDates(raw)

	var probe map[string]any
	if err := json.Unmarshal(raw, &probe); err != nil {
		return raw
	}

	// If already in v2 nested format, don't reshape.
	if _, hasDetail := probe["detail"]; hasDetail {
		return raw
	}
	if _, hasRecipients := probe["primary_recipients"]; hasRecipients {
		return raw
	}

	// Read flat fields commonly generated by conversational models.
	currency := "USD"
	if c, ok := probe["currency_code"].(string); ok && strings.TrimSpace(c) != "" {
		currency = strings.ToUpper(strings.TrimSpace(c))
	} else if c, ok := probe["currency"].(string); ok && strings.TrimSpace(c) != "" {
		currency = strings.ToUpper(strings.TrimSpace(c))
	}

	recipient := ""
	if r, ok := probe["recipient_email"].(string); ok {
		recipient = strings.TrimSpace(r)
	} else if r, ok := probe["recipient"].(string); ok {
		recipient = strings.TrimSpace(r)
	}

	note := ""
	if n, ok := probe["note"].(string); ok {
		note = strings.TrimSpace(n)
	}

	// Build items array
	var itemsOut []map[string]any
	if rawItems, ok := probe["items"].([]any); ok && len(rawItems) > 0 {
		for i, it := range rawItems {
			itMap, ok := it.(map[string]any)
			if !ok {
				continue
			}

			name := fmt.Sprintf("Item %d", i+1)
			if n, ok := itMap["name"].(string); ok && strings.TrimSpace(n) != "" {
				name = strings.TrimSpace(n)
			} else if d, ok := itMap["description"].(string); ok && strings.TrimSpace(d) != "" {
				name = strings.TrimSpace(d)
			}

			qtyStr := "1"
			if q, ok := itMap["quantity"].(string); ok && strings.TrimSpace(q) != "" {
				qtyStr = strings.TrimSpace(q)
			} else if qf, ok := itMap["quantity"].(float64); ok && qf > 0 {
				qtyStr = strconv.FormatFloat(qf, 'f', -1, 64)
			}

			// unit amount handling
			var unitVal string
			if uMap, ok := itMap["unit_amount"].(map[string]any); ok {
				if v, ok := uMap["value"].(string); ok {
					unitVal = v
				} else if vf, ok := uMap["value"].(float64); ok {
					unitVal = strconv.FormatFloat(vf, 'f', 2, 64)
				}
			} else if uStr, ok := itMap["unit_amount"].(string); ok {
				unitVal = strings.TrimSpace(uStr)
			} else if uNum, ok := itMap["unit_amount"].(float64); ok {
				unitVal = strconv.FormatFloat(uNum, 'f', 2, 64)
			}

			if unitVal == "" {
				unitVal = "0.00"
			}

			itemsOut = append(itemsOut, map[string]any{
				"name":     name,
				"quantity": qtyStr,
				"unit_amount": map[string]string{
					"currency_code": currency,
					"value":         unitVal,
				},
			})
		}
	}

	// If no items were parsed but a total is present, create a single item
	if len(itemsOut) == 0 {
		totalVal := "0.00"
		if t, ok := probe["total"].(string); ok && strings.TrimSpace(t) != "" {
			totalVal = strings.TrimSpace(t)
		} else if tf, ok := probe["total"].(float64); ok {
			totalVal = strconv.FormatFloat(tf, 'f', 2, 64)
		} else if a, ok := probe["amount"].(string); ok && strings.TrimSpace(a) != "" {
			totalVal = strings.TrimSpace(a)
		}

		itemsOut = append(itemsOut, map[string]any{
			"name":     "Invoice Services",
			"quantity": "1",
			"unit_amount": map[string]string{
				"currency_code": currency,
				"value":         totalVal,
			},
		})
	}

	// invoice_date was resolved by applyInvoiceDates above; carry it through.
	// It is always present and valid at this point, but fall back to today to
	// be safe if an upstream caller bypassed resolution.
	invoiceDate := time.Now().UTC().Format("2006-01-02")
	if d, ok := probe["invoice_date"].(string); ok && strings.TrimSpace(d) != "" {
		invoiceDate = strings.TrimSpace(d)
	}
	detail := map[string]any{
		"currency_code": currency,
		"invoice_date":  invoiceDate,
	}
	if note != "" {
		detail["note"] = note
	}

	out := map[string]any{
		"detail": detail,
		"items":  itemsOut,
	}

	if recipient != "" {
		out["primary_recipients"] = []map[string]any{
			{
				"billing_info": map[string]string{
					"email_address": recipient,
				},
			},
		}
	}

	if fallbackMerchantEmail != "" {
		out["invoicer"] = map[string]string{
			"email_address": fallbackMerchantEmail,
		}
	}

	res, err := json.Marshal(out)
	if err != nil {
		return raw
	}
	return res
}

// ScrubInvoicer replaces the seller (invoicer_*) fields of create_invoice
// arguments with the merchant's configured values. The model does not know
// the merchant's business details and tends to invent them ("123 Main St");
// left in place, they would be printed on the customer's invoice. Fields with
// no configured value are dropped so PayPal uses the account's own profile.
func ScrubInvoicer(raw json.RawMessage, merchantEmail, merchantName string) json.RawMessage {
	var args map[string]any
	if err := json.Unmarshal(raw, &args); err != nil {
		return raw
	}
	for k := range args {
		if strings.HasPrefix(k, "invoicer_") {
			delete(args, k)
		}
	}
	if merchantEmail != "" {
		args["invoicer_email_address"] = merchantEmail
	}
	if merchantName != "" {
		args["invoicer_business_name"] = merchantName
	}
	out, err := json.Marshal(args)
	if err != nil {
		return raw
	}
	return out
}
